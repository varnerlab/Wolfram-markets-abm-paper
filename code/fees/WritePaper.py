"""Generate manuscript fee comparisons from the validated, complete study."""
import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd


def pct(x, digits=2):
    return f"{100*x:.{digits}f}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("study", type=Path)
    parser.add_argument("--paper", type=Path, required=True)
    args = parser.parse_args()
    study = args.study.resolve(); paper = args.paper.resolve()
    validation = json.loads((study / "Validation.json").read_text())
    assert validation["complete"] and validation["simulations"] == 8400
    assert hashlib.sha256((study / "Run-Summary.csv").read_bytes()).hexdigest() == validation["summary_sha256"]
    summary = pd.read_csv(study / "Condition-Summary.csv")
    effects = pd.read_csv(study / "Paired-Effects.csv")
    def condition(fee, h, mode="endogenous", f=0.2):
        selected = summary[(summary.role == "treated") & (summary.fee_bps == fee)
            & (summary.h == h) & (summary.boundary == mode) & (summary.f == f)]
        assert len(selected) == 1
        return selected.iloc[0]
    def effect(fee, h, mode="endogenous", f=0.2):
        selected = effects[(effects.comparison == "fee_vs_zero") & (effects.fee_bps == fee)
            & (effects.h == h) & (effects.boundary == mode) & (effects.f == f)]
        assert len(selected) == 1
        return selected.iloc[0]
    generated = "% Generated by code/fees/WritePaper.py from transaction-fees-v1.\n"
    methods = r"""
We tested fees of 0, 5, 10, and 25 basis points on each completed buy or
sell to determine whether trading costs changed the response to the rule
switch. One basis point was 0.01\% of the base execution price. The rates
were chosen for a sensitivity comparison and were not calibrated to a
particular market. Fees applied from initialization, so different rates
could produce different financial histories before the rule switch.
Each condition used 50 starting markets on $64\times64$ grids, with
1,000 baseline steps and 3,000 subsequent steps. We tested all combinations
of fraction $f\in\{0.10,0.15,0.175,0.185,0.20,0.25\}$,
dealer depth $h\in\{0.1,1,100\}$, and technical traders active or held. For each fee
rate, dealer depth, and technical-trader condition, one no-switch control per
starting market retained the original rule and served all six
fractions. Each switched run shared its history with this
control up to the switch. This comparison used 8,400 simulations.
At each simulation step, we recorded the interior Sell fraction, the
dealer's quoted price, counts of completed orders and buy orders blocked
by insufficient cash, total trader cash, and cumulative dealer fee income.
We used these histories to identify Sell-majority formation and calculate
maximum drawdown after the rule switch. Fee income remained separate from
the dealer's trading reserves. We compared each switched run
with its no-switch control at the same fee rate. We also compared each positive fee
rate with zero fees under the same rule switch. Both comparisons matched
simulations by starting market and held other settings fixed. We used
2,000 bootstrap resamples of the 50 matched starting markets to obtain
percentile 95\% confidence intervals for these differences. Selected
comparisons appear in Supplementary Table~\ref{tab:transaction-fees}.
"""
    zero = condition(0, 100); charged = condition(25, 100); delta = effect(25, 100)
    near_zero = condition(0, 100, f=0.175); near_charged = condition(25, 100, f=0.175)
    near_delta = effect(25, 100, f=0.175)
    shallow_zero = condition(0, 1, f=0.175); shallow_charged = condition(25, 1, f=0.175)
    shallow_delta = effect(25, 1, f=0.175)
    probabilities = []
    for h in (0.1, 1.0, 100.0):
        values = [condition(fee, h).majority_probability for fee in (0, 5, 10, 25)]
        lo, hi = min(values), max(values)
        phrase = f"{lo:.2f}" if lo == hi else f"{lo:.2f}--{hi:.2f}"
        probabilities.append(f"{phrase} at {'' if probabilities else 'dealer depth '}$h={h:g}$")
    assert near_delta.majority_difference_lo < 0 < near_delta.majority_difference_hi
    assert delta.max_drawdown_difference_hi < 0 < shallow_delta.max_drawdown_difference_lo
    results = r"""
Finally, we asked whether trading costs changed the spread of selling or
its financial consequences, repeating the paired rule switch with fees
charged on completed orders. Because fees did not enter the interior
decision rule, the Sell fraction at every step and the final grid were
identical across all four fee rates and three dealer depths when
technical traders were held, for each starting market and fraction.
With technical traders active and fraction $f=0.20$, the Sell-majority
probability across fee rates was """ + ", ".join(probabilities[:-1]) + ", and " + probabilities[-1] + r"""
(Supplementary Table~\ref{tab:transaction-fees}). Nearer the crossover,
at fraction $f=0.175$ and dealer depth $h=100$, the probability changed
from """ + f"{near_zero.majority_probability:.2f}" + " without a fee to " + f"{near_charged.majority_probability:.2f}" + r""" at 25 basis points. The paired
difference was """ + f"{near_delta.majority_difference:.2f}" + r""" with a 95\% interval of [""" + f"{near_delta.majority_difference_lo:.2f}, {near_delta.majority_difference_hi:.2f}" + r"""],
so its direction was not resolved. The effect of fees on price declines
depended on the condition. At dealer depth $h=100$ and fraction $f=0.20$,
a 25-basis-point fee lowered the median maximum drawdown from """ + pct(zero.max_drawdown_median) + r"""\% to
""" + pct(charged.max_drawdown_median) + r"""\%, a median paired change of """ + pct(delta.max_drawdown_difference) + r""" percentage points with a
95\% interval of [""" + pct(delta.max_drawdown_difference_lo) + ", " + pct(delta.max_drawdown_difference_hi) + r"""]. At dealer depth $h=1$ and fraction
$f=0.175$, the same fee raised it from """ + pct(shallow_zero.max_drawdown_median) + r"""\% to """ + pct(shallow_charged.max_drawdown_median) + r"""\%, a
median paired change of """ + pct(shallow_delta.max_drawdown_difference) + r""" percentage points with a 95\% interval of
[""" + pct(shallow_delta.max_drawdown_difference_lo) + ", " + pct(shallow_delta.max_drawdown_difference_hi) + r"""]. Over a complete run, the fees accumulated: at 25 basis
points, dealer depth $h=100$, and fraction $f=0.20$, the median
cumulative fee income of the dealer was """ + pct(charged.fee_fraction_initial_trader_cash_median) + r"""\% of the traders' initial
cash (Supplementary Table~\ref{tab:transaction-fees}). Thus, fees did not
reduce price declines in every tested condition, and because the
decision rules were unchanged, any effect of fees on interior decisions
required active technical traders responding to the price.
"""
    table = r"""
\clearpage
\begin{center}
\begin{minipage}{\linewidth}\centering
\captionsetup{type=table,hypcap=false}
\caption{Transaction-fee comparisons. Each condition used 50 starting markets.
The fee was charged to each completed buyer and seller from initialization.
Sell-majority probabilities are followed by Wilson 95\% intervals.
In Panel A, drawdown and cumulative dealer fees are medians for the switched runs
at fraction $f=0.20$. Drawdown uses the 3,000-step post-switch observation period, including
the quoted price immediately before the switch. Fees include all 4,000 trading
steps and are expressed as a percentage of initial aggregate trader cash.
Fee income was held separately from trading reserves. Panel B reports
paired differences between 25 and zero basis points with percentile 95\%
intervals from 2,000 whole-market bootstrap samples. The probability difference
is a difference in proportions; drawdown differences are median paired
changes in percentage points. The complete
protocol, all six tested fractions, and paired differences are archived
with the transaction-fee study.}
\label{tab:transaction-fees}
\small\setlength{\tabcolsep}{3pt}
\begin{tabular}{r l r c c r r}
\toprule
\multicolumn{7}{l}{\textbf{A. Outcomes at each fee rate}}\\
$h$ & Technical & Fee (bp) & Majority, $f=0.175$ & Majority, $f=0.20$ & Drawdown (\%) & Fees (\%) \\
\midrule
"""
    for h in (0.1, 1.0, 100.0):
        for mode in ("hold", "endogenous"):
            for fee in (0, 5, 10, 25):
                near = condition(fee, h, mode, 0.175); high = condition(fee, h, mode)
                def prob(row):
                    return f"{row.majority_probability:.2f} [{row.majority_lo:.2f}, {row.majority_hi:.2f}]"
                table += f"{h:g} & {'held' if mode=='hold' else 'active'} & {fee} & {prob(near)} & {prob(high)} & "
                table += f"{pct(high.max_drawdown_median)} & {pct(high.fee_fraction_initial_trader_cash_median)} \\\\\n"
            table += "\\addlinespace\n"
    table += r"""\bottomrule
\end{tabular}

\medskip
\begin{tabular}{rrlrrl}
\toprule
\multicolumn{6}{l}{\textbf{B. Selected paired comparisons with technical traders active}}\\
$h$ & $f$ & Outcome & 0 bp & 25 bp & Paired difference [95\% CI]\\
\midrule
"""
    table += f"100 & 0.175 & Majority probability & {near_zero.majority_probability:.2f} & {near_charged.majority_probability:.2f} & "
    table += f"{near_delta.majority_difference:.2f} [{near_delta.majority_difference_lo:.2f}, {near_delta.majority_difference_hi:.2f}] \\\\\n"
    for h, fraction, first, last, difference in [(100, 0.20, zero, charged, delta),
                                                 (1, 0.175, shallow_zero, shallow_charged, shallow_delta)]:
        table += f"{h} & {fraction:g} & Drawdown (\\%) & {pct(first.max_drawdown_median)} & {pct(last.max_drawdown_median)} & "
        table += f"{pct(difference.max_drawdown_difference)} [{pct(difference.max_drawdown_difference_lo)}, {pct(difference.max_drawdown_difference_hi)}] \\\\\n"
    table += "\\bottomrule\n\\end{tabular}\n\\end{minipage}\n\\end{center}\n"
    supplement = r"""
\subsection{Transaction-fee comparison and validation}

The transaction-fee extension retained the original executed study and
used a separate versioned simulation snapshot. Its manifest specified all
8,400 simulations before execution. The run checked cash conservation
including the dealer's fee account, share conservation, nonnegative final
trader resources, positive finite prices, the constant product of trading
reserves, and the quoted price as their ratio. Dealer revenue was also checked
against fees on every completed buy and sale. Each switched run shared
its pre-switch financial and decision history with its no-switch control, including
the first post-switch price and fee collection. With technical traders
held, the complete Sell-fraction histories and final grids agreed exactly
across fee rates and dealer depths. Separate tests checked zero-fee equivalence to
the frozen original simulator, exhaustive feasible-quantity selection,
fee-inclusive affordability, isolated round trips, balanced orders, and
the zero-depth fixed-price case. Dealer fees were not available to fund
trading in any condition. The additional source snapshot, manifest,
per-run records, summaries, and validation report are stored in
\texttt{output/rebuilt/transaction-fees-v1/}. The manuscript additions
were generated from its validated summaries by
\texttt{code/fees/WritePaper.py}. The fee study varied neither market size
nor trader endowments and did not extend the observation period.
"""
    for name, content in [("methods", methods), ("results", results),
                          ("table", table), ("validation", supplement)]:
        (paper / "sections" / f"transaction-fees-{name}.tex").write_text(generated + content.lstrip())
    provenance = dict(writer_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        run_summary_sha256=validation["summary_sha256"],
        inputs={name:hashlib.sha256((study/name).read_bytes()).hexdigest()
            for name in ("Condition-Summary.csv", "Paired-Effects.csv", "Validation.json")})
    (study / "Manuscript-Generation.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print("Generated fee methods, results, table, and validation from the complete study.")


if __name__ == "__main__":
    main()
