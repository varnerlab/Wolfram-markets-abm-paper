    println(io, "AC(1)~ret = lag-1 autocorrelation of log returns;")
    println(io, "AC(1)~|ret| = lag-1 autocorrelation of absolute returns (volatility clustering);")
    println(io, "Tail~\$\\alpha\$ = Hill tail index (upper 10\\%).}")
    println(io, "\\label{tab:stylized-facts}")
    println(io, "\\begin{tabular}{lrrrrrrr}")
    println(io, "\\toprule")
    println(io, "& Mean & Std & Skewness & Ex.\\ kurtosis & AC(1) ret & AC(1) |ret| & Tail \$\\alpha\$ \\\\")
    println(io, "\\midrule")
    for (name, sf) in [("QQQ (real)", sf_QQQ), ("Model A", sf_A), ("Model B", sf_B)]
        println(io, @sprintf("%-14s & %7.4f & %7.4f & %6.3f & %8.2f & %8.4f & %8.4f & %6.2f \\\\", name, sf.μ, sf.σ, sf.skewness, sf.kurtosis, sf.ac1_ret, sf.ac1_abs, sf.tail_index))
    end
    println(io, "\\bottomrule")
    println(io, "\\end{tabular}")
    println(io, "\\end{table}")
end

