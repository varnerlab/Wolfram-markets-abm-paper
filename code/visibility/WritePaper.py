"""Write the visibility supplement from validated, frozen study outputs."""
import argparse
import hashlib
import json
from pathlib import Path
import pandas as pd
from Analyze import check_frozen

HEADER='% Generated by code/visibility/WritePaper.py from inventory-visibility-v1.\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('study',type=Path)
    parser.add_argument('--paper',type=Path,default=Path('paper-arxiv'))
    args=parser.parse_args();study=args.study.resolve();sections=args.paper.resolve()/'sections'
    protocol=json.loads((study/'Protocol.json').read_text())
    check_frozen(study,protocol)
    validation=json.loads((study/'Validation.json').read_text())
    assert validation['complete'] and validation['mode']=='main'
    for name,expected in validation['artifacts'].items():
        assert hashlib.sha256((study/name).read_bytes()).hexdigest()==expected,name
    branches=pd.read_csv(study/'Branch-Summary.csv')
    contrasts=pd.read_csv(study/'Contrasts.csv')
    def write(name,text):
        (sections/name).write_text(HEADER+text)
    def branch(boundary,h,mode,role,f=.2):
        rows=branches[(branches.boundary==boundary)&(branches.h==h)&
            (branches['mode']==mode)&(branches.role==role)]
        if role=='switch':
            rows=rows[rows.f==f]
        assert len(rows)==1
        return rows.iloc[0]

    methods=r'''\subsection{Inventory information and observed intentions}
\label{app:visibility}

The main model treated neighboring states as publicly communicated
intentions whose execution was unverified. We tested a hypothetical
information regime in which a trader knew whether a neighbor had any
shares and read Hold instead of Sell when that neighbor had none. This
comparison specified both the information available and the response to
it, without assuming that actual market participants could observe one
another's holdings. Let $q_j(t)$ be trader $j$'s shares after settlement
at step $t$, and let $s_j^{\rm in}(t)$ be the intention it would supply
to an interior neighbor under the original update order. The observation
mode was $v\in\{\mathrm{original},\mathrm{inventory}\}$, and the signal
read by a neighbor was $b_j^{(v)}(t)$, given by:
\begin{equation}
b_j^{(v)}(t)=
\begin{cases}
1, & v=\mathrm{inventory},\ s_j^{\rm in}(t)=2,\ q_j(t)=0,\\
s_j^{\rm in}(t), & \text{otherwise}.
\end{cases}
\label{eq:visible-signal}
\end{equation}
We replaced the inputs in the neighbor sum with these signals
(Eq.~\ref{eq:neighborhood-sum}). Hold contributed one to that sum; it
did not remove the neighbor. Orders still used stored intentions and
settled before the technical traders updated from price. We then
constructed the visible signals and updated interior intentions
together. The observation rule applied to interior and technical
senders and changed no stored intention directly. Selling the last
share therefore changed the signal read in the subsequent update,
while acquiring a share allowed a later Sell intention to be read
again. Buy signals were unchanged. Settlement and holdings could now
change subsequent neighbor inputs even with technical traders held,
providing a financial route into decisions that was absent under original
observations. We tested one response to knowledge
of inventory, without modeling a choice of announcements or strategic
misreporting.

Each market used grid size $L=64$, initial cash of 1,000 and ten shares
per trader, and 1,000 baseline steps with original observations and
Rule~19280. At step 1,001, four branches retained identical intentions,
cash, shares, dealer reserves, and technical-trader state: original or
inventory-conditioned observations, each with or without the rule switch.
The new observation rule also began in its no-switch control at that
step, so a change caused by the information regime alone was separated
from its effect on the response to the switch. Every branch continued
for 3,000 steps with reserve clearing, zero fees, and sales below
purchase cost allowed. We used 50 new starting markets, with seeds
730001 to 730050, technical traders held or active, and dealer depths
$h=1$ and 100. The initial switched fractions were $f=0.10$, 0.15,
0.175, 0.18, 0.20, and 0.25, with one no-switch control per observation
mode, depth, technical-trader condition, and starting market, giving
2,800 trajectories. Before these runs, we fixed an extension rule for
each depth and technical-trader condition: if inventory-conditioned
majority probability was below 0.75 at fraction $f=0.25$, add fractions
$f=0.35$, 0.50, 0.75, and 1.00 in both observation modes; if it was
above 0.25 at $f=0.10$, add $f=0.025$ and 0.05. Extensions used the same
starting markets and controls. Only this one extension round was
allowed. A two-market pilot used different seeds and supplied no
observations to the reported estimates. The primary setting and
outcome were fixed before the main runs and were unaffected by the
extension rule.

The primary outcome was the raw interior Sell fraction averaged over
the last 500 steps, at fraction $f=0.20$, dealer depth $h=100$, and with
technical traders held. Raw intentions were measured after the update,
so a reduction in visible Sell signals alone could not count as reduced
spreading. For starting market $k$, observation mode $v$, and switch
indicator $z$ (one for a switch, zero otherwise), the outcome was
$Y_{kvz}$. We defined the switch effect within each observation mode as
$\delta_{kv}$ and its mean change between observation modes as $\Delta$,
over $n=50$ starting markets, according to:
\begin{equation}
\delta_{kv}=Y_{kv1}-Y_{kv0},\qquad
\Delta=\frac{1}{n}\sum_{k=1}^{n}
\left(\delta_{k,\mathrm{inventory}}-\delta_{k,\mathrm{original}}\right).
\label{eq:visibility-contrast}
\end{equation}
We reported all four branch means and a two-sided percentile 95\%
interval for $\Delta$ from 10,000 bootstrap samples of whole starting
markets, retaining every matched branch and shared control. Secondary
outcomes were reaching a raw Sell majority, maximum quoted-price
drawdown including the quote before intervention, and completed interior
sales per interior trader. Their intervals and all other comparisons
were pointwise descriptions. Majority probabilities also had Wilson
95\% intervals. We did not estimate a precise crossover midpoint from
this coarse sweep or treat an interval containing zero as evidence of
equivalence. The intervals at added fractions were conditional on the
prescribed extension. For signal diagnostics, we divided the number
of interior Sell inputs sent by traders with zero shares by all
interior Sell inputs, counting each sender once per step and summing
over the specified period. Input signals
used holdings after settlement and were recorded before each update;
raw Sell fractions were recorded afterward. Through-onset diagnostics
included the inputs producing the first majority, or the full period
if no majority formed. Histories for the first starting market's
controls and fraction-$f=0.20$ branches at every depth and
technical-trader condition were selected before inspecting outcomes.

The study was archived in
\texttt{output/rebuilt/inventory-visibility-v1/}, with hashes of the
copied manuscript simulator, observation layer, analysis, manifests,
and package environment. Tests checked exact original-mode recovery,
unchanged signals when all sellers held shares, the last-share and
reacquisition cases, technical-sender signals, and update timing. An
original-mode full run reproduced the archived manuscript's final grid
exactly, and the existing reserve-clearing and round-trip tests passed.
All four branches shared identical pre-intervention state hashes and
histories through the first post-intervention quoted price. Every run
checked nonnegative holdings, cash and share conservation, positive
prices, and the dealer's constant product. RESULTS_VALIDATION
'''
    extension=json.loads((study/'Extension.json').read_text())
    cash=f"{validation['max_cash_error']:.2e}".split('e')
    product=f"{validation['max_product_error']:.2e}".split('e')
    last=(f"The extension added {extension['simulations']:,} trajectories, for "
          f"{validation['runs']:,} in total. The largest cash discrepancy was "
          rf"${cash[0]}\times10^{{{int(cash[1])}}}$ cash units, shares were conserved "
          "exactly, and the largest relative change in the reserve product was "
          rf"${product[0]}\times10^{{{int(product[1])}}}$.")
    methods=methods.replace('RESULTS_VALIDATION',last)

    caption=r'''\clearpage
\begin{center}
\begin{minipage}{\linewidth}\centering
\captionsetup{type=table,hypcap=false}
\caption{Inventory-conditioned signals at fraction $f=0.20$ over 50 new
starting markets and 3,000 post-intervention steps. Original observations
passed every intention; inventory-conditioned observations passed Hold
instead of Sell from a sender with no shares. Each mode had a switched
branch and a no-switch control with identical pre-intervention histories.
Entries are branch means, except majority entries, which count the
markets reaching a raw Sell fraction of one-half. Late Sell fraction
averages the final 500 steps. The final column is the inventory-conditioned
switch effect minus the original switch effect, with a percentile 95\%
interval from 10,000 bootstrap samples of whole starting markets
(Eq.~\ref{eq:visibility-contrast}). Differences in Panels A--C are
percentage points; Panel D uses completed sales per interior trader.
The primary outcome was Panel A with technical traders held and dealer
depth $h=100$; other comparisons are descriptive.}
\label{tab:visibility}
\small\setlength{\tabcolsep}{3pt}
\begin{tabular}{rlrrrrl}
\toprule
& & \multicolumn{2}{c}{Original signals} & \multicolumn{2}{c}{Inventory-conditioned} & \\
$h$ & Technical & Control & Switch & Control & Switch & Difference [95\% interval]\\
\midrule
'''
    parts=[caption]
    settings=[('final_sell_mean',100,r'A. Late raw Sell fraction (\%)'),
        ('majority',100,'B. Markets reaching a Sell majority (out of 50)'),
        ('max_drawdown',100,r'C. Mean maximum drawdown (\%)'),
        ('interior_sales_per_trader',1,'D. Mean completed sales per interior trader')]
    for metric,scale,title in settings:
        parts.append(r'\multicolumn{7}{l}{\textbf{'+title+r'}} \\'+'\n')
        for h in [1,100]:
            for boundary in ['hold','endogenous']:
                row=contrasts[(contrasts.h==h)&(contrasts.boundary==boundary)&
                    (contrasts.f==.2)&(contrasts.outcome==metric)].iloc[0]
                values=[row[k] for k in ['original_control','original_switch','inventory_control','inventory_switch']]
                numbers=[str(round(v*50)) if metric=='majority' else f'{v*scale:.2f}' for v in values]
                delta=f'{row.difference*scale:.2f} [{row.lower*scale:.2f}, {row.upper*scale:.2f}]'
                parts.append(' & '.join([str(h),'held' if boundary=='hold' else 'active']+numbers+[delta])+r' \\'+'\n')
        parts.append(r'\addlinespace'+'\n')
    original=branch('hold',100,'original','switch')
    parts.append(r'\bottomrule'+'\n'+r'\end{tabular}'+'\n'+r'\medskip\par\small'+'\n')
    parts.append("In the primary switched condition with original observations, traders with no shares supplied "
        +f"{original.unbacked_signal_fraction*100:.2f}\\% of all interior Sell inputs after the switch and "
        +f"{original.unbacked_through_onset*100:.2f}\\% through the first majority (averages over starting markets). "
        +"Inputs were measured after settlement and before the decision update. The full fraction sweep "
        +r"for this condition is shown in Supplementary Fig.~\ref{fig:visibility}."+'\n')
    parts.append(r'\end{minipage}'+'\n'+r'\end{center}'+'\n')
    write('visibility-table.tex',''.join(parts))

    write('visibility-figure.tex',r'''\clearpage
\begin{center}
\begin{minipage}{\linewidth}\centering
\captionsetup{type=figure,hypcap=false}
\includegraphics[width=\linewidth]{figs/FigS2-InventoryVisibility.pdf}
\caption{Inventory information in the primary setting: technical traders
held, dealer depth $h=100$, and grid size $L=64$. Black denotes original
signals and purple inventory-conditioned signals. Solid lines and points
denote switched markets; dashed horizontal lines denote the shared
no-switch controls. Each point used the same 50 starting markets and
3,000 post-intervention steps; joining lines guide the eye.
\textbf{(A)}~Probability of reaching a raw Sell majority, with Wilson
95\% intervals. \textbf{(B)}~Mean raw Sell fraction over the final 500
steps. \textbf{(C)}~Mean maximum quoted-price drawdown.
\textbf{(D)}~Mean completed sales per interior trader.
Bands in B--D are pointwise percentile 95\% intervals from 10,000
bootstrap samples of whole starting markets. The original sweep covered
fractions $f=0.10$ to 0.25; larger fractions were added under the
prespecified extension rule (Appendix~\ref{app:visibility}). Controls
retain Rule~19280 in both observation modes, so the change in control
outcomes measures the information intervention alone. The comparison
tests one hypothetical response to observing inventory.}
\label{fig:visibility}
\end{minipage}
\end{center}
''')
    primary=contrasts[contrasts.primary].iloc[0]
    drawdown=contrasts[(contrasts.boundary=='hold')&(contrasts.h==100)&
                      (contrasts.f==.2)&(contrasts.outcome=='max_drawdown')].iloc[0]
    inventory=branch('hold',100,'inventory','switch')
    high=branch('hold',100,'inventory','switch',.75)
    assert original.majority==1 and inventory.majority==0
    assert branch('hold',100,'inventory','switch',.5).majority==0
    results=rf'''With technical traders held, dealer depth $h=100$, and
fraction $f=0.20$, all 50 original switched markets reached a Sell
majority, compared with none under inventory-conditioned observations;
neither no-switch control condition produced a majority (Supplementary
Table~\ref{{tab:visibility}}). The mean raw Sell fraction over the final
500 steps was {100*primary.original_switch:.2f}\% with original signals
and {100*primary.inventory_switch:.2f}\% with inventory-conditioned
signals, compared with {100*primary.original_control:.2f}\% and
{100*primary.inventory_control:.2f}\% in their respective controls.
The primary paired contrast, the change in the switch effect between
observation modes, was {100*primary.difference:.2f} percentage points,
with a 95\% interval of [{100*primary.lower:.2f}, {100*primary.upper:.2f}].
In the original switched markets, zero-share traders supplied an
average of {100*original.unbacked_through_onset:.2f}\% of interior Sell
inputs through the first majority and
{100*original.unbacked_signal_fraction:.2f}\% over the full observation
period. The mean paired increase in drawdown over the no-switch control
fell from {100*drawdown.original_effect:.2f} to
{100*drawdown.inventory_effect:.2f} percentage points, while completed
sales per interior trader rose from
{original.interior_sales_per_trader:.2f} to
{inventory.interior_sales_per_trader:.2f}, so fewer selling intentions
did not mean fewer completed sales (Supplementary
Table~\ref{{tab:visibility}}). Extending the fraction sweep under the
prespecified rule found no inventory-conditioned majority at fraction
$f=0.50$ in this setting, but {round(high.majority*50)} of 50 markets
reached one at $f=0.75$, where the late mean raw Sell fraction was
{100*high.final_sell_mean:.2f}\% (Supplementary
Fig.~\ref{{fig:visibility}}). The observation rule therefore changed
both the response to a minority rule switch and the fractions at which
majorities were observed, while a first majority remained distinct from
a high late Sell fraction.
'''
    write('visibility-methods.tex',methods+'\n'+results)
    write('visibility-results.tex',rf'''When traders read Hold instead of a selling intention from a neighbor
with no shares, mean maximum drawdown fell from
{100*drawdown.original_switch:.2f}\% to {100*drawdown.inventory_switch:.2f}\%
in the comparison with technical traders held, dealer depth $h=100$,
and switched fraction $f=0.20$ (Supplementary
Fig.~\ref{{fig:visibility}}C and Table~\ref{{tab:visibility}}).
''')
    print('Wrote visibility supplement from validated outputs')

if __name__=='__main__':
    main()
