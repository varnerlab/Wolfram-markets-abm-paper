"""Generate the revision-timing and interior-technical tables and validation text.

Reads the complete, validated lazy-revision-interior-technical-v1 study and
writes sections/variants-table.tex, sections/variants-validation.tex, and
sections/variants-figure.tex (Supplementary Fig. S1, whose example markets are
chosen by Figs-Variants-MarketPanels.jl) in the paper directory. Prose that cites these numbers is hand-written.

Run: /opt/homebrew/bin/python3 code/variants/WritePaper.py \
         output/rebuilt/lazy-revision-interior-technical-v1 --paper paper-arxiv
"""
import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd

GENERATED = "% Generated by code/variants/WritePaper.py from lazy-revision-interior-technical-v1.\n"
TIMING = [1.0, 0.95, 0.9, 0.75, 0.5]
PLACEMENT = [("0", "None"), ("edge-count", "63 positions"), ("0.025", "2.5\\%"),
             ("0.05", "5\\%"), ("0.1", "10\\%")]


def sci(x):
    mantissa, exponent = f"{x:.1e}".split("e")
    return f"{mantissa}\\times10^{{{int(exponent)}}}"


def cid(L, r, rho, boundary, h):
    return f"L{L}-a{r:g}-r{rho}-{boundary}-h{h:g}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("study", type=Path)
    parser.add_argument("--paper", type=Path, required=True)
    args = parser.parse_args()
    study, paper = args.study.resolve(), args.paper.resolve()
    protocol = json.loads((study / "Protocol.json").read_text())
    status = json.loads((study / "Status.json").read_text())
    validation = json.loads((study / "Validation.json").read_text())
    assert status["state"] == "complete" and not protocol["version"].endswith("-smoke")
    for name, expected in protocol["frozen_files"].items():
        assert hashlib.sha256((study / name).read_bytes()).hexdigest() == expected, name
    assert validation["manifest_complete"] and validation["common_history_within_groups"]
    assert validation["archived_runs_compared"] == validation["archived_runs_reproduced"] > 0

    mid = pd.read_csv(study / "Midpoints.csv").set_index("condition")
    contrasts = pd.read_csv(study / "Contrasts.csv").set_index("contrast")
    summary = pd.read_csv(study / "Condition-Summary.csv")
    runs = pd.read_csv(study / "Run-Summary.csv", low_memory=False)

    def f50(condition):
        row = mid.loc[condition]
        return f"{row.f50:.3f} [{row.f50_low:.3f}, {row.f50_high:.3f}]"

    def width(condition):
        row = mid.loc[condition]
        return f"{row.width:.3f} [{row.width_low:.3f}, {row.width_high:.3f}]"

    def signed(x):
        text = f"{x:.3f}"
        return "0.000" if text == "-0.000" else text.replace("-", "$-$")

    def difference(label):
        row = contrasts.loc[label]
        return f"{signed(row.difference)} [{signed(row.low)}, {signed(row.high)}]"

    def halves(condition):
        """Largest median halves difference over the three fractions nearest f50."""
        rows = summary[summary.condition == condition]
        nearest = rows.iloc[(rows.f - mid.loc[condition].f50).abs().argsort()[:3]]
        return f"{nearest.median_half_gap_late.max():.3f}"

    def reach(rho):
        selected = runs[(runs.L == 64) & (runs.alpha == 1.0) & (runs.rho_label.astype(str) == rho)
                        & (runs.role == "treated")]
        return f"{100 * selected.technical_reach.mean():.1f}\\%"

    timing_rows = []
    for r in TIMING:
        held = cid(64, r, "0", "hold", 100)
        timing_rows.append(" & ".join([
            f"{r:g}", f50(held), f50(cid(64, r, "0", "endogenous", 1)),
            f50(cid(64, r, "0", "endogenous", 100)),
            difference(f"lazy alpha={r:g}: active h=100 minus held"), halves(held)]) + r" \\")
    size_rows = [" & ".join([f"{L}", f50(cid(L, 0.9, "0", "hold", 100)),
                             width(cid(L, 0.9, "0", "hold", 100))]) + r" \\" for L in (32, 64, 128)]
    placement_rows = []
    for rho, name in PLACEMENT:
        placement_rows.append(" & ".join([
            name, reach(rho), f50(cid(64, 1, rho, "hold", 100)),
            f50(cid(64, 1, rho, "endogenous", 1)), f50(cid(64, 1, rho, "endogenous", 100)),
            difference(f"interior rho={rho}: active h=100 minus held")]) + r" \\")
    placement_size_rows = [" & ".join([
        f"{L}", "", f50(cid(L, 1, "0.05", "hold", 100)), "",
        f50(cid(L, 1, "0.05", "endogenous", 100)),
        difference(f"size L={L}: rho=0.05 active h=100 minus held")]) + r" \\" for L in (32, 64, 128)]
    control_majorities = int(runs[runs.role == "control"].majority.sum())
    assert control_majorities == 0, control_majorities
    unresolved = validation["unresolved_conditions"]
    assert unresolved == ["L128-a1-r0.05-hold-h100"], unresolved

    tables = GENERATED + r"""\clearpage
\begin{center}
\begin{minipage}{\linewidth}\centering
\captionsetup{type=table,hypcap=false}
\caption{Revision timing. At each step, each interior trader adopted its rule's output with revision probability $r$ and otherwise kept its current intention; $r=1$ is the main model. Entries are the interpolated fraction $f_{50}$ at which half of 50 starting markets reached a Sell majority within 3,000 post-switch steps, with 95\% intervals in brackets from 2,000 bootstrap samples of whole starting markets, drawn once and shared by all conditions. Active $-$ held is the difference in $f_{50}$ at dealer depth $h=100$, from the same samples. Halves is the largest median, over the three tested fractions nearest the held $f_{50}$, of the absolute difference between the Sell fractions of the two checkerboard halves of the grid, averaged over five snapshots in the last 400 steps. Panel B uses technical traders held at dealer depth $h=100$ and revision probability $r=0.9$; the width is $f_{75}-f_{25}$. No no-switch control reached a Sell majority in any condition.}
\label{tab:variants-timing}
\scriptsize\setlength{\tabcolsep}{2.5pt}
\begin{tabular}{rlllll}
\toprule
\multicolumn{6}{l}{\textbf{A. Grid size $L=64$}} \\
$r$ & Held & Active, $h=1$ & Active, $h=100$ & Active $-$ held, $h=100$ & Halves \\
\midrule
""" + "\n".join(timing_rows) + r"""
\midrule
\multicolumn{6}{l}{\textbf{B. Revision probability $r=0.9$, technical traders held}} \\
$L$ & Held & Width & & & \\
\midrule
""" + "\n".join(size_rows) + r"""
\bottomrule
\end{tabular}
\end{minipage}
\end{center}

\begin{center}
\begin{minipage}{\linewidth}\centering
\captionsetup{type=table,hypcap=false}
\caption{Technical traders inside the grid, with revision probability $r=1$. In addition to the technical traders along the edge, band-rule technical traders occupied a fraction $\rho$ of interior positions, excluding the traders given the new rule; the row of 63 positions adds as many interior technical traders as there are along the edge. Reach is the mean fraction of the other interior traders with at least one technical trader among their four neighbors. Entries are interpolated $f_{50}$ over 50 starting markets and 3,000 post-switch steps, with 95\% intervals in brackets from 2,000 bootstrap samples of whole starting markets shared by all conditions; active $-$ held is the difference in $f_{50}$ at dealer depth $h=100$. Panel B uses interior fraction $\rho=0.05$. At grid size $L=128$ with technical traders held, majority probability rose steeply enough that only three tested fractions had probabilities strictly between 0.05 and 0.95. No no-switch control reached a Sell majority in any condition.}
\label{tab:variants-placement}
\scriptsize\setlength{\tabcolsep}{2.5pt}
\begin{tabular}{llllll}
\toprule
\multicolumn{6}{l}{\textbf{A. Grid size $L=64$}} \\
Interior & Reach & Held & Active, $h=1$ & Active, $h=100$ & Active $-$ held, $h=100$ \\
\midrule
""" + "\n".join(placement_rows) + r"""
\midrule
\multicolumn{6}{l}{\textbf{B. Interior fraction $\rho=0.05$}} \\
$L$ & & Held & & Active, $h=100$ & Active $-$ held \\
\midrule
""" + "\n".join(placement_size_rows) + r"""
\bottomrule
\end{tabular}
\end{minipage}
\end{center}
"""

    simulations = protocol["full_financial_simulations"]
    groups = protocol["groups"]
    appendix = GENERATED + rf"""\subsection{{Revision timing and interior technical traders}}
\label{{app:variants}}

The revision-timing and interior-technical-trader comparisons used a
separate versioned study, \texttt{{output/rebuilt/{protocol["version"]}/}},
whose manifest fixed all {simulations:,} simulations in {groups:,} groups
before execution. Each group comprised one no-switch control and the
switched runs at 22 fractions placed around the crossover found in a
20-market pilot of the same condition. With revision probability $r=1$
and no interior technical traders the simulation is the main model, and the
{validation["archived_runs_reproduced"]:,} runs of this study
that repeated a condition of the manuscript campaigns reproduced the
archived final grids exactly. Every switched run shared its control's
history through the first quoted price after the switch, and cash and
share conservation held in every run, with a largest cash discrepancy of
${sci(validation["max_cash_conservation_error"])}$. Whether a trader revised
its intention at a step was decided by a counter-based draw from the
simulation seed, step, and trader, so paired runs used identical draws and
the generator used for initialization was unaffected. Interior technical
positions were ranked by a counter-based score of the seed and position,
which did not depend on the fraction $f$, and the selection of traders for
the new rule skipped those positions. Midpoint intervals used 2,000
bootstrap samples of whole starting markets drawn once for all conditions,
so differences between conditions sharing starting markets were paired.
One condition, grid size $L=128$ with interior fraction $\rho=0.05$ and
technical traders held, had three rather than five tested fractions with
majority probabilities strictly between 0.05 and 0.95
(Supplementary Table~\ref{{tab:variants-placement}}).
"""

    selection = pd.read_csv(study / "FigS1-Selection.csv")
    assert len(selection) == 5 and list(selection.majority) == [False, False, True, True, True]
    picks = selection.drop_duplicates("f")
    fractions = f"$f={picks.f.iat[0]:.3f}$, " + ", ".join(f"{x:.3f}" for x in picks.f.iloc[1:-1]) \
        + f", and {picks.f.iat[-1]:.3f}"
    def listed(values):
        values = [f"{x:.2f}" for x in values]
        return ", ".join(values[:-1]) + ", and " + values[-1]
    seeds = ", ".join(str(x) for x in selection.seed.iloc[:-1]) + f", and {selection.seed.iat[-1]}"
    figure = GENERATED + r"""\clearpage
\setcounter{figure}{0}
\renewcommand{\thefigure}{S\arabic{figure}}
\begin{center}
\begin{minipage}{\linewidth}
\captionsetup{type=figure,hypcap=false}
\centering
\includegraphics[width=0.87\linewidth]{figs/FigS1-RevisionMarketPanels.pdf}
\caption{Five example markets with revision probability $r=0.9$, active
technical traders, and dealer depth $h=100$ over 3,000 post-switch steps,
the counterpart of Fig.~\ref{fig:dose-panels} without the separate
checkerboard halves of the main model. Blue, gray, and orange denote Buy,
Hold, and Sell. The fractions """ + fractions + r""" were the tested
fractions whose majority probabilities at revision probability $r=0.9$ (""" + listed(picks.probability) + r""")
were nearest those of the fractions in Fig.~\ref{fig:dose-panels} at $r=1$
(""" + listed(picks.fig4_probability) + r"""), with ties broken by proximity to the
$r=0.9$ midpoint. Within each fraction and outcome, the market nearest the
median onset, or the median final Sell fraction for markets without a
majority, was selected from the campaign summaries before any images were
inspected, with the starting-market number breaking ties.
\textbf{(A)}~Grid decisions at the rule switch and after 500, 1,500, and
3,000 steps. Starting markets were """ + seeds + r""", from left to right.
\textbf{(B)}~Quoted price divided by its value at the rule switch.
\textbf{(C)}~Interior Sell fraction, with one-half marked by a horizontal
line. Midpoints and widths appear in Supplementary
Table~\ref{tab:variants-timing}.}
\label{fig:variants-panels}
\end{minipage}
\end{center}
"""
    (paper / "sections" / "variants-figure.tex").write_text(figure)
    (paper / "sections" / "variants-table.tex").write_text(tables)
    (paper / "sections" / "variants-validation.tex").write_text(appendix)
    print("wrote", paper / "sections" / "variants-table.tex")
    print("wrote", paper / "sections" / "variants-validation.tex")
    print("wrote", paper / "sections" / "variants-figure.tex")


if __name__ == "__main__":
    main()
